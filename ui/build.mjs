import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('..', import.meta.url));
const ui = fileURLToPath(new URL('.', import.meta.url));
const temporary = await mkdtemp(join(tmpdir(), 'sub2api-helper-css-'));
const output = join(root, 'helper/static/style.css');
const attribution = '/*! Generated by ui/build.mjs. Upstream styles: Wei-Shaw/sub2api frontend/src/style.css and tailwind.config.js, commit 15871f904056f548dd874a1d069ffc6cdf777b78 (LGPL-3.0). See ui/ and THIRD_PARTY_NOTICES.md. */\n';
try {
  const source = await readFile(join(ui, 'upstream.css'), 'utf8');
  const adapters = await readFile(join(ui, 'adapters.css'), 'utf8');
  const input = join(temporary, 'input.css');
  await writeFile(input, source + '\n' + adapters);
  const result = spawnSync(process.execPath, [join(ui, 'node_modules/tailwindcss/lib/cli.js'),
    '--config', join(ui, 'tailwind.config.js'), '--input', input, '--output', output, '--minify'],
    { cwd: root, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exitCode = result.status || 1;
  else await writeFile(output, attribution + await readFile(output, 'utf8'));
} finally {
  await rm(temporary, { recursive: true, force: true });
}
